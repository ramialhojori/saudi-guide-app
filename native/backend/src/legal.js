const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
function html(doc) {
  const d = LEGAL[doc];
  return `<!doctype html><html lang="ar" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${esc(d.title)} — دليل السعودية</title>
<style>body{margin:0;background:#F4F1EE;color:#2B2745;font-family:-apple-system,'IBM Plex Sans Arabic',Tahoma,sans-serif;line-height:1.9}main{max-width:760px;margin:0 auto;padding:28px 20px 60px}h1{color:#604C87;margin:0 0 4px}small{color:#6B6585}h2{font-size:18px;margin:26px 0 6px;color:#2B2745}ul{padding-right:20px;margin:0}li{margin:4px 0}.card{background:#fff;border-radius:20px;padding:6px 20px 16px;margin-top:14px}</style></head>
<body><main><h1>${esc(d.title)}</h1><small>دليل السعودية · آخر تحديث ${LEGAL_DATE}</small><p>${esc(d.intro)}</p>
${d.sections.map(([h, items]) => `<div class="card"><h2>${esc(h)}</h2><ul>${items.map((x) => `<li>${esc(x)}</li>`).join('')}</ul></div>`).join('')}
<p><small>للتواصل: من داخل التطبيق ← الإعدادات ← تواصل معنا.</small></p></main></body></html>`;
}

export function legalRoute(p, J) {
  let m = p.match(/^\/v1\/legal\/(privacy|terms|community)$/);
  if (m) return J({ ...LEGAL[m[1]], date: LEGAL_DATE }, 200, 3600);
  m = p.match(/^\/(privacy|terms)$/);
  if (m) return new Response(html(m[1]), { headers: { 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'public, max-age=3600' } });
  return null;
}
