const MS = STARTS.map((s) => Date.UTC(+s.slice(0, 4), +s.slice(5, 7) - 1, +s.slice(8, 10)));

export const HIJRI_MONTHS = ['محرم', 'صفر', 'ربيع الأول', 'ربيع الآخر', 'جمادى الأولى', 'جمادى الآخرة', 'رجب', 'شعبان', 'رمضان', 'شوال', 'ذو القعدة', 'ذو الحجة'];
export const HIJRI_MONTHS_EN = ['Muharram', 'Safar', 'Rabi I', 'Rabi II', 'Jumada I', 'Jumada II', 'Rajab', "Sha'ban", 'Ramadan', 'Shawwal', "Dhu al-Qa'dah", 'Dhu al-Hijjah'];

export type HDate = { y: number; m: number; d: number };

/** يوم ميلادي (YYYY-MM-DD) → هجري. خارج الجدول يرجع null */
export function toHijri(day: string): HDate | null {
  const t = Date.UTC(+day.slice(0, 4), +day.slice(5, 7) - 1, +day.slice(8, 10));
  if (t < MS[0] || day >= END) return null;
  let i = MS.length - 1;
  while (i > 0 && MS[i] > t) i--;
  return { y: FIRST_YEAR + Math.floor(i / 12), m: (i % 12) + 1, d: Math.round((t - MS[i]) / 86400e3) + 1 };
}

export const hijriMonthName = (m: number) => (isEn ? HIJRI_MONTHS_EN : HIJRI_MONTHS)[m - 1] || '';
/** «6 جمادى الأولى 1448هـ» */
export function hijriLabel(day: string, withYear = true): string {
  const h = toHijri(day);
  if (!h) return '';
  return isEn ? `${h.d} ${hijriMonthName(h.m)}${withYear ? ' ' + h.y + ' AH' : ''}` : `${h.d} ${hijriMonthName(h.m)}${withYear ? ' ' + h.y + 'هـ' : ''}`;
}
